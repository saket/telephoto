  @Test fun flip_entire_image() {
    // Horizontal flip - when flipping the entire image, it should stay in the same bounds
    // but the internal content would be mirrored (this test is about bounds transformation)
    IntRect(
      topLeft = IntOffset.Zero,
      bottomRight = IntOffset(x = 4032, y = 3024)
    ).let { original ->
      assertThat(original.flipRegionHorizontally(parent = original)).isEqualTo(
        IntRect(
          topLeft = IntOffset.Zero,
          bottomRight = IntOffset(x = 4032, y = 3024)
        )
      )
    }

    // Vertical flip (180° rotation + horizontal flip) - dimensions stay same
    IntRect(
      topLeft = IntOffset.Zero,
      bottomRight = IntOffset(x = 3024, y = 4032)
    ).let { original ->
      assertThat(original.flipVertically(unRotatedParent = original)).isEqualTo(
        IntRect(
          topLeft = IntOffset.Zero,
          bottomRight = IntOffset(x = 3024, y = 4032)
        )
      )
    }

    // Test horizontal flip with a sub-rectangle to see actual coordinate transformation
    val landscape = IntRect(
      topLeft = IntOffset.Zero,
      bottomRight = IntOffset(x = 1600, y = 800)
    )

    // Right half should become left half when flipped
    val rightHalf = IntRect(
      topLeft = IntOffset(x = 800, y = 0),
      bottomRight = IntOffset(x = 1600, y = 800)
    )

    assertThat(rightHalf.flipRegionHorizontally(parent = landscape)).isEqualTo(
      IntRect(
        topLeft = IntOffset(x = 0, y = 0),
        bottomRight = IntOffset(x = 800, y = 800)
      )
    )

    // Transpose (90° + horizontal flip) - dimensions swap like 90° rotation
    IntRect(
      topLeft = IntOffset.Zero,
      bottomRight = IntOffset(x = 1600, y = 800)
    ).let { original ->
      assertThat(original.transposeBy(unRotatedParent = original)).isEqualTo(
        IntRect(
          topLeft = IntOffset.Zero,
          bottomRight = IntOffset(x = 800, y = 1600)
        )
      )
    }

    // Transverse (270° + horizontal flip) - dimensions swap like 270° rotation
    IntRect(
      topLeft = IntOffset.Zero,
      bottomRight = IntOffset(x = 1600, y = 800)
    ).let { original ->
      assertThat(original.transverseBy(unRotatedParent = original)).isEqualTo(
        IntRect(
          topLeft = IntOffset.Zero,
          bottomRight = IntOffset(x = 800, y = 1600)
        )
      )
    }
  }

  @Test fun flip_parts_of_an_image() {
    val landscape = IntRect(
      topLeft = IntOffset.Zero,
      bottomRight = IntOffset(x = 1600, y = 800)
    )

    // Test simple horizontal flip - mirror X coordinates
    val rightQuadrant = IntRect(
      topLeft = IntOffset(x = 800, y = 0),
      bottomRight = IntOffset(x = 1600, y = 400),
    )
    assertThat(rightQuadrant.flipRegionHorizontally(parent = landscape)).isEqualTo(
      IntRect(
        topLeft = IntOffset(x = 0, y = 0),        // X mirrored: 1600 - 1600 = 0
        bottomRight = IntOffset(x = 800, y = 400), // X mirrored: 1600 - 800 = 800
      )
    )

    // Test vertical flip - mirror both X and Y coordinates
    val centerRect = IntRect(
      topLeft = IntOffset(x = 400, y = 200),
      bottomRight = IntOffset(x = 1200, y = 600),
    )
    assertThat(centerRect.flipVertically(unRotatedParent = landscape)).isEqualTo(
      IntRect(
        topLeft = IntOffset(x = 400, y = 200),    // X: 1600-1200=400, Y: 800-600=200
        bottomRight = IntOffset(x = 1200, y = 600), // X: 1600-400=1200, Y: 800-200=600
      )
    )

    // Test transpose using actual rotateBy + flip logic
    val bottomLeftQuad = IntRect(
      topLeft = IntOffset(x = 0, y = 400),
      bottomRight = IntOffset(x = 800, y = 800),
    )

    // First rotate by 90°, then flip horizontally
    val rotated90 = bottomLeftQuad.rotateRegionBy(90, landscape)
    val transposed = rotated90.flipRegionHorizontally(
      parent = IntRect(IntOffset.Zero, IntSize(landscape.height, landscape.width)),
    )

    assertThat(bottomLeftQuad.transposeBy(landscape)).isEqualTo(transposed)

    // Test transverse using actual rotateBy + flip logic
    val centerSquare = IntRect(
      offset = IntOffset(x = 400, y = 200),
      size = IntSize(400, 400)
    )

    // First rotate by 270°, then flip horizontally
    val rotated270 = centerSquare.rotateRegionBy(270, landscape)
    val transversed = rotated270.flipRegionHorizontally(
      parent = IntRect(IntOffset.Zero, IntSize(landscape.height, landscape.width)),
    )

    assertThat(centerSquare.transverseBy(landscape)).isEqualTo(transversed)

    // Test chaining operations
    assertThat(
      rightQuadrant
        .flipRegionHorizontally(parent = landscape)
        .flipRegionHorizontally(parent = landscape)
    ).isEqualTo(rightQuadrant)
  }

