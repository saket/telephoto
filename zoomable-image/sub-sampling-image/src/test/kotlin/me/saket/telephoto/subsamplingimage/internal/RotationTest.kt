  @Test fun `rotation matrix ensures no gaps between tiles`() {
    val viewportBounds = Size(1080f, 2400f)
    val imageSize = Size(2700f, 6000f)

    val tiles = ImageRegionTileGrid.generate(
      viewportSize = viewportBounds.discardFractionalParts(),
      unscaledImageSize = imageSize.discardFractionalParts(),
    ).foreground.values.single()

    val matrix = createRotationMatrix(
      bitmapSize = imageSize,
      exif = ExifMetadata(ImageOrientation.None, flippedHorizontally = false),
      bounds = viewportBounds
    )

    val mappedTiles = tiles.map { tile ->
      matrix.mapRect(tile.bounds.toRect())
    }

    // Verify no gaps.
    val totalArea = mappedTiles.sumOf { (it.width * it.height).toDouble() }.toFloat()
    val expectedArea = viewportBounds.width * viewportBounds.height
    assertThat(totalArea).isEqualTo(expectedArea)
  }

  private fun android.graphics.Matrix.mapRect(rect: Rect): Rect {
    val rectF = rect.toAndroidRectF()
    mapRect(rectF)
    return rectF.toRect().toComposeRect()
  }
}

private fun IntRect.flipVertically(unRotatedParent: IntRect): IntRect {
  return IntRect(
    topLeft = IntOffset(
      x = unRotatedParent.width - bottomRight.x,
      y = unRotatedParent.height - bottomRight.y
    ),
    bottomRight = IntOffset(
      x = unRotatedParent.width - topLeft.x,
      y = unRotatedParent.height - topLeft.y
    )
  )
}

private fun IntRect.transposeBy(unRotatedParent: IntRect): IntRect {
  if (this == unRotatedParent) {
    return IntRect(
      topLeft = IntOffset.Zero,
      bottomRight = IntOffset(x = unRotatedParent.height, y = unRotatedParent.width)
    )
  }

  // Transpose = 90° rotation + horizontal flip
  val rotated = rotateRegionBy(90, unRotatedParent)
  val rotatedParent = IntRect(IntOffset.Zero, IntSize(unRotatedParent.height, unRotatedParent.width))
  return rotated.flipRegionHorizontally(parent = rotatedParent)
}

private fun IntRect.transverseBy(unRotatedParent: IntRect): IntRect {
  if (this == unRotatedParent) {
    return IntRect(
      topLeft = IntOffset.Zero,
      bottomRight = IntOffset(x = unRotatedParent.height, y = unRotatedParent.width)
    )
  }

  // Transverse = 270° rotation + horizontal flip
  val rotated = rotateRegionBy(270, unRotatedParent)
  val rotatedParent = IntRect(IntOffset.Zero, IntSize(unRotatedParent.height, unRotatedParent.width))
  return rotated.flipRegionHorizontally(parent = rotatedParent)
}
